// Compile contracts/src/*.cash with cashc 0.14 into contracts/artifacts/*.json and the
// sdk's embedded copies (sdk/src/artifacts/*.ts). `--check` fails if any copy is stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFile } from 'cashc';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sdkArt = path.join(root, '..', 'sdk', 'src', 'artifacts');
const check = process.argv.includes('--check');
const names = ['Lane', 'Arena', 'Counter', 'Sale'];
let stale = 0;

const writeIf = (file, text) => {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (old === text) return;
  stale++;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`${check ? 'stale, rewrote' : 'wrote'} ${path.relative(path.join(root, '..'), file)}`);
};

for (const n of names) {
  const a = compileFile(path.join(root, 'src', `${n}.cash`));
  delete a.updatedAt; // keep artifacts byte stable between compiles
  const json = JSON.stringify(a, null, 2) + '\n';
  writeIf(path.join(root, 'artifacts', `${n}.json`), json);
  writeIf(path.join(sdkArt, `${n}.ts`), `// Generated by contracts/scripts/compile.mjs from contracts/src/${n}.cash. Do not edit.\nconst artifact = ${json.trim()};\nexport default artifact;\n`);
}
console.log(`compiled ${names.join(', ')}${stale ? ` (${stale} file(s) updated)` : ' (up to date)'}`);
